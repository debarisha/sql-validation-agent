"""Generate data-validation SQL from a mapping file.

Usage:
    python generator/generate_sql.py mappings/contract.yaml
    python generator/generate_sql.py --all            # every mappings/*.yaml

Writes five files to generated_sql/<table>/. Never connects to a database.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
SUPPORTED_DIALECTS = {"sqlserver"}
DATE_TYPES = {"date", "datetime", "datetime2", "smalldatetime", "datetimeoffset", "time"}
FLOAT_TYPES = {"float", "real"}
IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


class MappingError(ValueError):
    pass


# --------------------------------------------------------------------------- mapping

def load_mapping(path: Path) -> dict:
    with path.open(encoding="utf-8") as f:
        m = yaml.safe_load(f) or {}

    for field in ("table", "dialect", "source", "target", "key", "columns"):
        if field not in m:
            raise MappingError(f"{path}: missing required field '{field}'")

    if m["dialect"] not in SUPPORTED_DIALECTS:
        raise MappingError(f"{path}: dialect '{m['dialect']}' not supported "
                           f"(supported: {', '.join(sorted(SUPPORTED_DIALECTS))})")

    cols = m["columns"]
    if not isinstance(cols, list) or not cols:
        raise MappingError(f"{path}: 'columns' must be a non-empty list")
    names = []
    allowed = {"name", "type", "required", "compare"}
    for c in cols:
        if not isinstance(c, dict) or "name" not in c:
            raise MappingError(f"{path}: every column needs a 'name'")
        unknown = set(c) - allowed
        if unknown:
            raise MappingError(
                f"{path}: column '{c['name']}' has unknown field(s) {sorted(map(str, unknown))}. "
                "If a type has a comma, quote it, e.g. type: \"decimal(18,2)\"")
        c.setdefault("type", "nvarchar")
        c.setdefault("required", False)
        c.setdefault("compare", True)
        names.append(c["name"])

    keys = m["key"] if isinstance(m["key"], list) else [m["key"]]
    if not keys:
        raise MappingError(f"{path}: 'key' must list at least one column")
    for k in keys:
        if k not in names:
            raise MappingError(f"{path}: key column '{k}' is not listed under 'columns'")
    m["key"] = keys

    col_map = m.get("column_map") or {}
    for src_name in col_map:
        if src_name not in names:
            raise MappingError(f"{path}: column_map entry '{src_name}' is not listed under 'columns'")
    m["column_map"] = col_map

    for ident in names + list(col_map.values()):
        if not IDENT.match(str(ident)):
            raise MappingError(f"{path}: '{ident}' is not a plain identifier")
    for tbl in (m["source"], m["target"]):
        if not all(IDENT.match(p) for p in str(tbl).split(".")):
            raise MappingError(f"{path}: table name '{tbl}' must look like schema.table")

    m["_path"] = path.relative_to(ROOT).as_posix() if path.is_relative_to(ROOT) else str(path)
    return m


# --------------------------------------------------------------------------- helpers

def q(name: str) -> str:
    """Bracket-quote an identifier for T-SQL."""
    return f"[{name}]"


def qt(table: str) -> str:
    return ".".join(q(p) for p in table.split("."))


def tgt_name(m: dict, src_col: str) -> str:
    return m["column_map"].get(src_col, src_col)


def base_type(t: str) -> str:
    return str(t).split("(")[0].strip().lower()


def as_text(expr: str, col_type: str) -> str:
    """Convert a value to NVARCHAR in a way that keeps comparisons meaningful."""
    bt = base_type(col_type)
    if bt in DATE_TYPES:
        return f"CONVERT(NVARCHAR(40), {expr}, 121)"      # ISO, full precision
    if bt in FLOAT_TYPES:
        return f"CONVERT(NVARCHAR(40), {expr}, 3)"        # 17 significant digits
    return f"CAST({expr} AS NVARCHAR(MAX))"


def header(m: dict, filename: str, check: str, passing: str, notes: list[str] | None = None) -> str:
    lines = [
        f"/* {filename}",
        f"   Mapping : {m['_path']}  (dialect: {m['dialect']})",
        f"   Source  : {m['source']}",
        f"   Target  : {m['target']}",
        f"   Check   : {check}",
        f"   PASS    : {passing}",
        "   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;",
        "             change the mapping and regenerate.",
    ]
    for n in notes or []:
        lines.append(f"             {n}")
    lines[-1] += " */"
    return "\n".join(lines) + "\n\n"


# --------------------------------------------------------------------------- checks

def gen_row_count(m: dict) -> str:
    h = header(m, "01_row_count.sql", "Total row count, source vs target.",
               "One row with row_count_diff = 0 (status = 'PASS').")
    return h + f"""SELECT
    s.src_row_count,
    t.tgt_row_count,
    s.src_row_count - t.tgt_row_count AS row_count_diff,
    CASE WHEN s.src_row_count = t.tgt_row_count THEN 'PASS' ELSE 'FAIL' END AS status
FROM       (SELECT COUNT_BIG(*) AS src_row_count FROM {qt(m['source'])}) AS s
CROSS JOIN (SELECT COUNT_BIG(*) AS tgt_row_count FROM {qt(m['target'])}) AS t;
"""


def gen_null_checks(m: dict) -> str:
    required = [c["name"] for c in m["columns"] if c["required"]]
    optional = [c["name"] for c in m["columns"] if not c["required"]]
    h = header(m, "02_null_checks.sql",
               "NULL count per column on each side.",
               "Every row with is_required = 1 has null_count = 0 (status = 'PASS').",
               [f"Required: {', '.join(required) or '(none)'}",
                f"Optional (INFO only): {', '.join(optional) or '(none)'}"])

    def side_cte(cte: str, table: str, use_tgt_names: bool) -> str:
        sums = []
        for i, c in enumerate(m["columns"]):
            phys = tgt_name(m, c["name"]) if use_tgt_names else c["name"]
            sums.append(f"        SUM(CASE WHEN {q(phys)} IS NULL THEN 1 ELSE 0 END) AS c{i}")
        return (f"{cte} AS (\n    SELECT\n        COUNT_BIG(*) AS total_rows,\n"
                + ",\n".join(sums) + f"\n    FROM {qt(table)}\n)")

    values = ",\n".join(
        f"        ('{c['name']}', {1 if c['required'] else 0}, n.c{i})"
        for i, c in enumerate(m["columns"]))

    def branch(side: str, cte: str) -> str:
        return (f"    SELECT '{side}' AS side, v.column_name, v.is_required, "
                f"ISNULL(v.null_count, 0) AS null_count, n.total_rows\n"
                f"    FROM {cte} AS n\n    CROSS APPLY (VALUES\n{values}\n"
                f"    ) AS v(column_name, is_required, null_count)")

    return h + f"""WITH {side_cte('src_nulls', m['source'], False)},
{side_cte('tgt_nulls', m['target'], True)},
unpivoted AS (
{branch('source', 'src_nulls')}
    UNION ALL
{branch('target', 'tgt_nulls')}
)
SELECT
    side,
    column_name,
    is_required,
    null_count,
    total_rows,
    CASE
        WHEN is_required = 1 AND null_count > 0 THEN 'FAIL'
        WHEN is_required = 1                    THEN 'PASS'
        ELSE 'INFO'
    END AS status
FROM unpivoted
ORDER BY side, is_required DESC, column_name;
"""


def gen_duplicates(m: dict) -> str:
    keys = m["key"]
    src_keys = ", ".join(q(k) for k in keys)
    tgt_sel = ", ".join(f"{q(tgt_name(m, k))} AS {q(k)}" if tgt_name(m, k) != k else q(k) for k in keys)
    tgt_grp = ", ".join(q(tgt_name(m, k)) for k in keys)
    h = header(m, "03_duplicate_checks.sql",
               f"Key values ({', '.join(keys)}) that appear more than once, on each side.",
               "No rows returned.",
               ["NULL keys are grouped together; they are also reported by 02_null_checks.sql."])
    return h + f"""SELECT 'source' AS side, {src_keys}, COUNT_BIG(*) AS occurrences
FROM {qt(m['source'])}
GROUP BY {src_keys}
HAVING COUNT_BIG(*) > 1

UNION ALL

SELECT 'target' AS side, {tgt_sel}, COUNT_BIG(*) AS occurrences
FROM {qt(m['target'])}
GROUP BY {tgt_grp}
HAVING COUNT_BIG(*) > 1

ORDER BY side, {src_keys};
"""


def gen_missing_extra(m: dict) -> str:
    keys = m["key"]
    k0 = q(keys[0])
    src_sel = ", ".join(q(k) for k in keys)
    tgt_sel = ", ".join(f"{q(tgt_name(m, k))} AS {q(k)}" if tgt_name(m, k) != k else q(k) for k in keys)
    src_nn = " AND ".join(f"{q(k)} IS NOT NULL" for k in keys)
    tgt_nn = " AND ".join(f"{q(tgt_name(m, k))} IS NOT NULL" for k in keys)
    join = "\n   AND ".join(f"s.{q(k)} = t.{q(k)}" for k in keys)
    out_keys = ",\n    ".join(f"COALESCE(s.{q(k)}, t.{q(k)}) AS {q(k)}" for k in keys)
    h = header(m, "04_missing_extra.sql",
               f"Keys ({', '.join(keys)}) that exist on only one side. "
               "MISSING_IN_TARGET = source only; EXTRA_IN_TARGET = target only.",
               "No rows returned.",
               ["DISTINCT keys are used so duplicates (see 03) do not repeat rows here.",
                "Rows with a NULL key never match; they are reported by 02_null_checks.sql."])
    return h + f"""WITH s AS (SELECT DISTINCT {src_sel} FROM {qt(m['source'])} WHERE {src_nn}),
     t AS (SELECT DISTINCT {tgt_sel} FROM {qt(m['target'])} WHERE {tgt_nn})
SELECT
    {out_keys},
    CASE WHEN t.{k0} IS NULL THEN 'MISSING_IN_TARGET'
         ELSE 'EXTRA_IN_TARGET' END AS issue
FROM s
FULL OUTER JOIN t
    ON {join}
WHERE s.{k0} IS NULL
   OR t.{k0} IS NULL
ORDER BY issue, {", ".join(q(k) for k in keys)};
"""


def gen_column_compare(m: dict) -> str:
    keys = m["key"]
    cmp_cols = [c for c in m["columns"] if c["compare"] and c["name"] not in keys]
    h = header(m, "05_column_compare.sql",
               f"For keys on both sides, compares {', '.join(c['name'] for c in cmp_cols) or '(no columns)'} value by value.",
               "No rows returned. Each returned row is one (key, column) mismatch.",
               ["NULL-safe: NULL vs NULL matches; NULL vs a value is a mismatch.",
                "Values compared as NVARCHAR: dates use ISO style 121, float/real use style 3.",
                "Trailing spaces are ignored and case follows the database collation.",
                "If keys are duplicated (see 03), result rows multiply."])
    if not cmp_cols:
        return h + "-- No columns are marked compare: true in the mapping.\nSELECT TOP (0) 1 AS nothing_to_compare;\n"

    key_sel = ",\n    ".join(f"s.{q(k)}" for k in keys)
    join = "\n   AND ".join(f"s.{q(k)} = t.{q(tgt_name(m, k))}" for k in keys)
    width = max(len(c["name"]) for c in cmp_cols) + 3
    values = ",\n".join(
        f"    ({(repr(c['name']) + ',').ljust(width)} "
        f"{as_text('s.' + q(c['name']), c['type'])}, "
        f"{as_text('t.' + q(tgt_name(m, c['name'])), c['type'])})"
        for c in cmp_cols)
    order = ", ".join(f"s.{q(k)}" for k in keys)
    return h + f"""SELECT
    {key_sel},
    v.column_name,
    v.src_value,
    v.tgt_value
FROM {qt(m['source'])} AS s
INNER JOIN {qt(m['target'])} AS t
    ON {join}
CROSS APPLY (VALUES
{values}
) AS v(column_name, src_value, tgt_value)
WHERE EXISTS (SELECT v.src_value EXCEPT SELECT v.tgt_value)   -- NULL-safe "is different"
ORDER BY {order}, v.column_name;
"""


GENERATORS = {
    "01_row_count.sql": gen_row_count,
    "02_null_checks.sql": gen_null_checks,
    "03_duplicate_checks.sql": gen_duplicates,
    "04_missing_extra.sql": gen_missing_extra,
    "05_column_compare.sql": gen_column_compare,
}


def generate(mapping_path: Path, out_root: Path) -> list[Path]:
    m = load_mapping(mapping_path)
    out_dir = out_root / str(m["table"]).lower()
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, fn in GENERATORS.items():
        p = out_dir / name
        p.write_text(fn(m), encoding="utf-8", newline="\n")
        written.append(p)
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate validation SQL from mapping YAML files.")
    ap.add_argument("mappings", nargs="*", type=Path, help="mapping YAML file(s)")
    ap.add_argument("--all", action="store_true", help="use every mappings/*.yaml")
    ap.add_argument("--out", type=Path, default=ROOT / "generated_sql", help="output root folder")
    args = ap.parse_args(argv)

    paths = sorted((ROOT / "mappings").glob("*.yaml")) if args.all else args.mappings
    if not paths:
        ap.error("give a mapping file or --all")

    rc = 0
    for p in paths:
        try:
            for w in generate(p.resolve(), args.out.resolve()):
                print(f"wrote {w.relative_to(ROOT) if w.is_relative_to(ROOT) else w}")
        except (MappingError, OSError, yaml.YAMLError) as e:
            print(f"ERROR: {e}", file=sys.stderr)
            rc = 1
    return rc


if __name__ == "__main__":
    sys.exit(main())
