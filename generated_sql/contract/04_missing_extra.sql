/* 04_missing_extra.sql
   Mapping : mappings/contract.yaml  (dialect: sqlserver)
   Source  : src.Contract
   Target  : tgt.Contract
   Check   : Keys (ContractID) that exist on only one side. MISSING_IN_TARGET = source only; EXTRA_IN_TARGET = target only.
   PASS    : No rows returned.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             DISTINCT keys are used so duplicates (see 03) do not repeat rows here.
             Rows with a NULL key never match; they are reported by 02_null_checks.sql. */

WITH s AS (SELECT DISTINCT [ContractID] FROM [src].[Contract] WHERE [ContractID] IS NOT NULL),
     t AS (SELECT DISTINCT [ContractID] FROM [tgt].[Contract] WHERE [ContractID] IS NOT NULL)
SELECT
    COALESCE(s.[ContractID], t.[ContractID]) AS [ContractID],
    CASE WHEN t.[ContractID] IS NULL THEN 'MISSING_IN_TARGET'
         ELSE 'EXTRA_IN_TARGET' END AS issue
FROM s
FULL OUTER JOIN t
    ON s.[ContractID] = t.[ContractID]
WHERE s.[ContractID] IS NULL
   OR t.[ContractID] IS NULL
ORDER BY issue, [ContractID];
