/* 02_null_checks.sql
   Mapping : mappings/contract.yaml  (dialect: sqlserver)
   Source  : src.Contract
   Target  : tgt.Contract
   Check   : NULL count per column on each side.
   PASS    : Every row with is_required = 1 has null_count = 0 (status = 'PASS').
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             Required: ContractID, CustomerID, StartDate, Amount
             Optional (INFO only): EndDate, Status */

WITH src_nulls AS (
    SELECT
        COUNT_BIG(*) AS total_rows,
        SUM(CASE WHEN [ContractID] IS NULL THEN 1 ELSE 0 END) AS c0,
        SUM(CASE WHEN [CustomerID] IS NULL THEN 1 ELSE 0 END) AS c1,
        SUM(CASE WHEN [StartDate] IS NULL THEN 1 ELSE 0 END) AS c2,
        SUM(CASE WHEN [EndDate] IS NULL THEN 1 ELSE 0 END) AS c3,
        SUM(CASE WHEN [Amount] IS NULL THEN 1 ELSE 0 END) AS c4,
        SUM(CASE WHEN [Status] IS NULL THEN 1 ELSE 0 END) AS c5
    FROM [src].[Contract]
),
tgt_nulls AS (
    SELECT
        COUNT_BIG(*) AS total_rows,
        SUM(CASE WHEN [ContractID] IS NULL THEN 1 ELSE 0 END) AS c0,
        SUM(CASE WHEN [CustomerID] IS NULL THEN 1 ELSE 0 END) AS c1,
        SUM(CASE WHEN [StartDate] IS NULL THEN 1 ELSE 0 END) AS c2,
        SUM(CASE WHEN [EndDate] IS NULL THEN 1 ELSE 0 END) AS c3,
        SUM(CASE WHEN [Amount] IS NULL THEN 1 ELSE 0 END) AS c4,
        SUM(CASE WHEN [Status] IS NULL THEN 1 ELSE 0 END) AS c5
    FROM [tgt].[Contract]
),
unpivoted AS (
    SELECT 'source' AS side, v.column_name, v.is_required, ISNULL(v.null_count, 0) AS null_count, n.total_rows
    FROM src_nulls AS n
    CROSS APPLY (VALUES
        ('ContractID', 1, n.c0),
        ('CustomerID', 1, n.c1),
        ('StartDate', 1, n.c2),
        ('EndDate', 0, n.c3),
        ('Amount', 1, n.c4),
        ('Status', 0, n.c5)
    ) AS v(column_name, is_required, null_count)
    UNION ALL
    SELECT 'target' AS side, v.column_name, v.is_required, ISNULL(v.null_count, 0) AS null_count, n.total_rows
    FROM tgt_nulls AS n
    CROSS APPLY (VALUES
        ('ContractID', 1, n.c0),
        ('CustomerID', 1, n.c1),
        ('StartDate', 1, n.c2),
        ('EndDate', 0, n.c3),
        ('Amount', 1, n.c4),
        ('Status', 0, n.c5)
    ) AS v(column_name, is_required, null_count)
)
SELECT
    side,
    column_name,
    is_required,
    null_count,
    total_rows,
    CASE
        WHEN is_required = 1 AND null_count > 0 THEN 'FAIL'
        WHEN is_required = 1                    THEN 'PASS'
        ELSE 'INFO'
    END AS status
FROM unpivoted
ORDER BY side, is_required DESC, column_name;
