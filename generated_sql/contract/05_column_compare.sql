/* 05_column_compare.sql
   Mapping : mappings/contract.yaml  (dialect: sqlserver)
   Source  : src.Contract
   Target  : tgt.Contract
   Check   : For keys on both sides, compares CustomerID, StartDate, EndDate, Amount, Status value by value.
   PASS    : No rows returned. Each returned row is one (key, column) mismatch.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             NULL-safe: NULL vs NULL matches; NULL vs a value is a mismatch.
             Values compared as NVARCHAR: dates use ISO style 121, float/real use style 3.
             Trailing spaces are ignored and case follows the database collation.
             If keys are duplicated (see 03), result rows multiply. */

SELECT
    s.[ContractID],
    v.column_name,
    v.src_value,
    v.tgt_value
FROM [src].[Contract] AS s
INNER JOIN [tgt].[Contract] AS t
    ON s.[ContractID] = t.[ContractID]
CROSS APPLY (VALUES
    ('CustomerID', CAST(s.[CustomerID] AS NVARCHAR(MAX)), CAST(t.[CustomerID] AS NVARCHAR(MAX))),
    ('StartDate',  CONVERT(NVARCHAR(40), s.[StartDate], 121), CONVERT(NVARCHAR(40), t.[StartDate], 121)),
    ('EndDate',    CONVERT(NVARCHAR(40), s.[EndDate], 121), CONVERT(NVARCHAR(40), t.[EndDate], 121)),
    ('Amount',     CAST(s.[Amount] AS NVARCHAR(MAX)), CAST(t.[Amount] AS NVARCHAR(MAX))),
    ('Status',     CAST(s.[Status] AS NVARCHAR(MAX)), CAST(t.[Status] AS NVARCHAR(MAX)))
) AS v(column_name, src_value, tgt_value)
WHERE EXISTS (SELECT v.src_value EXCEPT SELECT v.tgt_value)   -- NULL-safe "is different"
ORDER BY s.[ContractID], v.column_name;
