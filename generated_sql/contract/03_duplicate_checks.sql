/* 03_duplicate_checks.sql
   Mapping : mappings/contract.yaml  (dialect: sqlserver)
   Source  : src.Contract
   Target  : tgt.Contract
   Check   : Key values (ContractID) that appear more than once, on each side.
   PASS    : No rows returned.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             NULL keys are grouped together; they are also reported by 02_null_checks.sql. */

SELECT 'source' AS side, [ContractID], COUNT_BIG(*) AS occurrences
FROM [src].[Contract]
GROUP BY [ContractID]
HAVING COUNT_BIG(*) > 1

UNION ALL

SELECT 'target' AS side, [ContractID], COUNT_BIG(*) AS occurrences
FROM [tgt].[Contract]
GROUP BY [ContractID]
HAVING COUNT_BIG(*) > 1

ORDER BY side, [ContractID];
