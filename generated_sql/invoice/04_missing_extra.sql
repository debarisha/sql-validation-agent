/* 04_missing_extra.sql
   Mapping : mappings/invoice.yaml  (dialect: sqlserver)
   Source  : src.Invoice
   Target  : tgt.Invoice
   Check   : Keys (InvoiceID) that exist on only one side. MISSING_IN_TARGET = source only; EXTRA_IN_TARGET = target only.
   PASS    : No rows returned.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             DISTINCT keys are used so duplicates (see 03) do not repeat rows here.
             Rows with a NULL key never match; they are reported by 02_null_checks.sql. */

WITH s AS (SELECT DISTINCT [InvoiceID] FROM [src].[Invoice] WHERE [InvoiceID] IS NOT NULL),
     t AS (SELECT DISTINCT [InvoiceID] FROM [tgt].[Invoice] WHERE [InvoiceID] IS NOT NULL)
SELECT
    COALESCE(s.[InvoiceID], t.[InvoiceID]) AS [InvoiceID],
    CASE WHEN t.[InvoiceID] IS NULL THEN 'MISSING_IN_TARGET'
         ELSE 'EXTRA_IN_TARGET' END AS issue
FROM s
FULL OUTER JOIN t
    ON s.[InvoiceID] = t.[InvoiceID]
WHERE s.[InvoiceID] IS NULL
   OR t.[InvoiceID] IS NULL
ORDER BY issue, [InvoiceID];
