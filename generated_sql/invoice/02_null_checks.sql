/* 02_null_checks.sql
   Mapping : mappings/invoice.yaml  (dialect: sqlserver)
   Source  : src.Invoice
   Target  : tgt.Invoice
   Check   : NULL count per column on each side.
   PASS    : Every row with is_required = 1 has null_count = 0 (status = 'PASS').
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             Required: InvoiceID, CustomerNo, InvoiceDate, Amount, Currency
             Optional (INFO only): DueDate, Status, Notes, ExchangeRate, UpdatedAt */

WITH src_nulls AS (
    SELECT
        COUNT_BIG(*) AS total_rows,
        SUM(CASE WHEN [InvoiceID] IS NULL THEN 1 ELSE 0 END) AS c0,
        SUM(CASE WHEN [CustomerNo] IS NULL THEN 1 ELSE 0 END) AS c1,
        SUM(CASE WHEN [InvoiceDate] IS NULL THEN 1 ELSE 0 END) AS c2,
        SUM(CASE WHEN [DueDate] IS NULL THEN 1 ELSE 0 END) AS c3,
        SUM(CASE WHEN [Amount] IS NULL THEN 1 ELSE 0 END) AS c4,
        SUM(CASE WHEN [Currency] IS NULL THEN 1 ELSE 0 END) AS c5,
        SUM(CASE WHEN [Status] IS NULL THEN 1 ELSE 0 END) AS c6,
        SUM(CASE WHEN [Notes] IS NULL THEN 1 ELSE 0 END) AS c7,
        SUM(CASE WHEN [ExchangeRate] IS NULL THEN 1 ELSE 0 END) AS c8,
        SUM(CASE WHEN [UpdatedAt] IS NULL THEN 1 ELSE 0 END) AS c9
    FROM [src].[Invoice]
),
tgt_nulls AS (
    SELECT
        COUNT_BIG(*) AS total_rows,
        SUM(CASE WHEN [InvoiceID] IS NULL THEN 1 ELSE 0 END) AS c0,
        SUM(CASE WHEN [CustomerNumber] IS NULL THEN 1 ELSE 0 END) AS c1,
        SUM(CASE WHEN [InvoiceDate] IS NULL THEN 1 ELSE 0 END) AS c2,
        SUM(CASE WHEN [DueDate] IS NULL THEN 1 ELSE 0 END) AS c3,
        SUM(CASE WHEN [Amount] IS NULL THEN 1 ELSE 0 END) AS c4,
        SUM(CASE WHEN [Currency] IS NULL THEN 1 ELSE 0 END) AS c5,
        SUM(CASE WHEN [Status] IS NULL THEN 1 ELSE 0 END) AS c6,
        SUM(CASE WHEN [Notes] IS NULL THEN 1 ELSE 0 END) AS c7,
        SUM(CASE WHEN [ExchangeRate] IS NULL THEN 1 ELSE 0 END) AS c8,
        SUM(CASE WHEN [UpdatedAt] IS NULL THEN 1 ELSE 0 END) AS c9
    FROM [tgt].[Invoice]
),
unpivoted AS (
    SELECT 'source' AS side, v.column_name, v.is_required, ISNULL(v.null_count, 0) AS null_count, n.total_rows
    FROM src_nulls AS n
    CROSS APPLY (VALUES
        ('InvoiceID', 1, n.c0),
        ('CustomerNo', 1, n.c1),
        ('InvoiceDate', 1, n.c2),
        ('DueDate', 0, n.c3),
        ('Amount', 1, n.c4),
        ('Currency', 1, n.c5),
        ('Status', 0, n.c6),
        ('Notes', 0, n.c7),
        ('ExchangeRate', 0, n.c8),
        ('UpdatedAt', 0, n.c9)
    ) AS v(column_name, is_required, null_count)
    UNION ALL
    SELECT 'target' AS side, v.column_name, v.is_required, ISNULL(v.null_count, 0) AS null_count, n.total_rows
    FROM tgt_nulls AS n
    CROSS APPLY (VALUES
        ('InvoiceID', 1, n.c0),
        ('CustomerNo', 1, n.c1),
        ('InvoiceDate', 1, n.c2),
        ('DueDate', 0, n.c3),
        ('Amount', 1, n.c4),
        ('Currency', 1, n.c5),
        ('Status', 0, n.c6),
        ('Notes', 0, n.c7),
        ('ExchangeRate', 0, n.c8),
        ('UpdatedAt', 0, n.c9)
    ) AS v(column_name, is_required, null_count)
)
SELECT
    side,
    column_name,
    is_required,
    null_count,
    total_rows,
    CASE
        WHEN is_required = 1 AND null_count > 0 THEN 'FAIL'
        WHEN is_required = 1                    THEN 'PASS'
        ELSE 'INFO'
    END AS status
FROM unpivoted
ORDER BY side, is_required DESC, column_name;
