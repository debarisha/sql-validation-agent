/* 01_row_count.sql
   Mapping : mappings/invoice.yaml  (dialect: sqlserver)
   Source  : src.Invoice
   Target  : tgt.Invoice
   Check   : Total row count, source vs target.
   PASS    : One row with row_count_diff = 0 (status = 'PASS').
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate. */

SELECT
    s.src_row_count,
    t.tgt_row_count,
    s.src_row_count - t.tgt_row_count AS row_count_diff,
    CASE WHEN s.src_row_count = t.tgt_row_count THEN 'PASS' ELSE 'FAIL' END AS status
FROM       (SELECT COUNT_BIG(*) AS src_row_count FROM [src].[Invoice]) AS s
CROSS JOIN (SELECT COUNT_BIG(*) AS tgt_row_count FROM [tgt].[Invoice]) AS t;
