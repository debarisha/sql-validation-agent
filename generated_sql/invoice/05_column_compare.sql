/* 05_column_compare.sql
   Mapping : mappings/invoice.yaml  (dialect: sqlserver)
   Source  : src.Invoice
   Target  : tgt.Invoice
   Check   : For keys on both sides, compares CustomerNo, InvoiceDate, DueDate, Amount, Currency, Status, Notes, ExchangeRate value by value.
   PASS    : No rows returned. Each returned row is one (key, column) mismatch.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             NULL-safe: NULL vs NULL matches; NULL vs a value is a mismatch.
             Values compared as NVARCHAR: dates use ISO style 121, float/real use style 3.
             Trailing spaces are ignored and case follows the database collation.
             If keys are duplicated (see 03), result rows multiply. */

SELECT
    s.[InvoiceID],
    v.column_name,
    v.src_value,
    v.tgt_value
FROM [src].[Invoice] AS s
INNER JOIN [tgt].[Invoice] AS t
    ON s.[InvoiceID] = t.[InvoiceID]
CROSS APPLY (VALUES
    ('CustomerNo',   CAST(s.[CustomerNo] AS NVARCHAR(MAX)), CAST(t.[CustomerNumber] AS NVARCHAR(MAX))),
    ('InvoiceDate',  CONVERT(NVARCHAR(40), s.[InvoiceDate], 121), CONVERT(NVARCHAR(40), t.[InvoiceDate], 121)),
    ('DueDate',      CONVERT(NVARCHAR(40), s.[DueDate], 121), CONVERT(NVARCHAR(40), t.[DueDate], 121)),
    ('Amount',       CAST(s.[Amount] AS NVARCHAR(MAX)), CAST(t.[Amount] AS NVARCHAR(MAX))),
    ('Currency',     CAST(s.[Currency] AS NVARCHAR(MAX)), CAST(t.[Currency] AS NVARCHAR(MAX))),
    ('Status',       CAST(s.[Status] AS NVARCHAR(MAX)), CAST(t.[Status] AS NVARCHAR(MAX))),
    ('Notes',        CAST(s.[Notes] AS NVARCHAR(MAX)), CAST(t.[Notes] AS NVARCHAR(MAX))),
    ('ExchangeRate', CONVERT(NVARCHAR(40), s.[ExchangeRate], 3), CONVERT(NVARCHAR(40), t.[ExchangeRate], 3))
) AS v(column_name, src_value, tgt_value)
WHERE EXISTS (SELECT v.src_value EXCEPT SELECT v.tgt_value)   -- NULL-safe "is different"
ORDER BY s.[InvoiceID], v.column_name;
