/* 03_duplicate_checks.sql
   Mapping : mappings/invoice.yaml  (dialect: sqlserver)
   Source  : src.Invoice
   Target  : tgt.Invoice
   Check   : Key values (InvoiceID) that appear more than once, on each side.
   PASS    : No rows returned.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             NULL keys are grouped together; they are also reported by 02_null_checks.sql. */

SELECT 'source' AS side, [InvoiceID], COUNT_BIG(*) AS occurrences
FROM [src].[Invoice]
GROUP BY [InvoiceID]
HAVING COUNT_BIG(*) > 1

UNION ALL

SELECT 'target' AS side, [InvoiceID], COUNT_BIG(*) AS occurrences
FROM [tgt].[Invoice]
GROUP BY [InvoiceID]
HAVING COUNT_BIG(*) > 1

ORDER BY side, [InvoiceID];
