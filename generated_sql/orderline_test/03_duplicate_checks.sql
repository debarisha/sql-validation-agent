/* 03_duplicate_checks.sql
   Mapping : mappings/orderline_test.yaml  (dialect: sqlserver)
   Source  : stg.OrderLine
   Target  : dw.OrderLine
   Check   : Key values (OrderID, LineNo) that appear more than once, on each side.
   PASS    : No rows returned.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             NULL keys are grouped together; they are also reported by 02_null_checks.sql. */

SELECT 'source' AS side, [OrderID], [LineNo], COUNT_BIG(*) AS occurrences
FROM [stg].[OrderLine]
GROUP BY [OrderID], [LineNo]
HAVING COUNT_BIG(*) > 1

UNION ALL

SELECT 'target' AS side, [OrderID], [LineNumber] AS [LineNo], COUNT_BIG(*) AS occurrences
FROM [dw].[OrderLine]
GROUP BY [OrderID], [LineNumber]
HAVING COUNT_BIG(*) > 1

ORDER BY side, [OrderID], [LineNo];
