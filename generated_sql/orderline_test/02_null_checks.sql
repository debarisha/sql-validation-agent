/* 02_null_checks.sql
   Mapping : mappings/orderline_test.yaml  (dialect: sqlserver)
   Source  : stg.OrderLine
   Target  : dw.OrderLine
   Check   : NULL count per column on each side.
   PASS    : Every row with is_required = 1 has null_count = 0 (status = 'PASS').
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             Required: OrderID, LineNo, ProductCode, Qty, UnitPrice
             Optional (INFO only): Discount, ShipDate */

WITH src_nulls AS (
    SELECT
        COUNT_BIG(*) AS total_rows,
        SUM(CASE WHEN [OrderID] IS NULL THEN 1 ELSE 0 END) AS c0,
        SUM(CASE WHEN [LineNo] IS NULL THEN 1 ELSE 0 END) AS c1,
        SUM(CASE WHEN [ProductCode] IS NULL THEN 1 ELSE 0 END) AS c2,
        SUM(CASE WHEN [Qty] IS NULL THEN 1 ELSE 0 END) AS c3,
        SUM(CASE WHEN [UnitPrice] IS NULL THEN 1 ELSE 0 END) AS c4,
        SUM(CASE WHEN [Discount] IS NULL THEN 1 ELSE 0 END) AS c5,
        SUM(CASE WHEN [ShipDate] IS NULL THEN 1 ELSE 0 END) AS c6
    FROM [stg].[OrderLine]
),
tgt_nulls AS (
    SELECT
        COUNT_BIG(*) AS total_rows,
        SUM(CASE WHEN [OrderID] IS NULL THEN 1 ELSE 0 END) AS c0,
        SUM(CASE WHEN [LineNumber] IS NULL THEN 1 ELSE 0 END) AS c1,
        SUM(CASE WHEN [ProductCode] IS NULL THEN 1 ELSE 0 END) AS c2,
        SUM(CASE WHEN [Qty] IS NULL THEN 1 ELSE 0 END) AS c3,
        SUM(CASE WHEN [UnitPrice] IS NULL THEN 1 ELSE 0 END) AS c4,
        SUM(CASE WHEN [Discount] IS NULL THEN 1 ELSE 0 END) AS c5,
        SUM(CASE WHEN [ShipDate] IS NULL THEN 1 ELSE 0 END) AS c6
    FROM [dw].[OrderLine]
),
unpivoted AS (
    SELECT 'source' AS side, v.column_name, v.is_required, ISNULL(v.null_count, 0) AS null_count, n.total_rows
    FROM src_nulls AS n
    CROSS APPLY (VALUES
        ('OrderID', 1, n.c0),
        ('LineNo', 1, n.c1),
        ('ProductCode', 1, n.c2),
        ('Qty', 1, n.c3),
        ('UnitPrice', 1, n.c4),
        ('Discount', 0, n.c5),
        ('ShipDate', 0, n.c6)
    ) AS v(column_name, is_required, null_count)
    UNION ALL
    SELECT 'target' AS side, v.column_name, v.is_required, ISNULL(v.null_count, 0) AS null_count, n.total_rows
    FROM tgt_nulls AS n
    CROSS APPLY (VALUES
        ('OrderID', 1, n.c0),
        ('LineNo', 1, n.c1),
        ('ProductCode', 1, n.c2),
        ('Qty', 1, n.c3),
        ('UnitPrice', 1, n.c4),
        ('Discount', 0, n.c5),
        ('ShipDate', 0, n.c6)
    ) AS v(column_name, is_required, null_count)
)
SELECT
    side,
    column_name,
    is_required,
    null_count,
    total_rows,
    CASE
        WHEN is_required = 1 AND null_count > 0 THEN 'FAIL'
        WHEN is_required = 1                    THEN 'PASS'
        ELSE 'INFO'
    END AS status
FROM unpivoted
ORDER BY side, is_required DESC, column_name;
