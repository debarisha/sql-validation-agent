/* 05_column_compare.sql
   Mapping : mappings/orderline_test.yaml  (dialect: sqlserver)
   Source  : stg.OrderLine
   Target  : dw.OrderLine
   Check   : For keys on both sides, compares ProductCode, Qty, UnitPrice, Discount, ShipDate value by value.
   PASS    : No rows returned. Each returned row is one (key, column) mismatch.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             NULL-safe: NULL vs NULL matches; NULL vs a value is a mismatch.
             Values compared as NVARCHAR: dates use ISO style 121, float/real use style 3.
             Trailing spaces are ignored and case follows the database collation.
             If keys are duplicated (see 03), result rows multiply. */

SELECT
    s.[OrderID],
    s.[LineNo],
    v.column_name,
    v.src_value,
    v.tgt_value
FROM [stg].[OrderLine] AS s
INNER JOIN [dw].[OrderLine] AS t
    ON s.[OrderID] = t.[OrderID]
   AND s.[LineNo] = t.[LineNumber]
CROSS APPLY (VALUES
    ('ProductCode', CAST(s.[ProductCode] AS NVARCHAR(MAX)), CAST(t.[ProductCode] AS NVARCHAR(MAX))),
    ('Qty',         CAST(s.[Qty] AS NVARCHAR(MAX)), CAST(t.[Qty] AS NVARCHAR(MAX))),
    ('UnitPrice',   CAST(s.[UnitPrice] AS NVARCHAR(MAX)), CAST(t.[UnitPrice] AS NVARCHAR(MAX))),
    ('Discount',    CONVERT(NVARCHAR(40), s.[Discount], 3), CONVERT(NVARCHAR(40), t.[Discount], 3)),
    ('ShipDate',    CONVERT(NVARCHAR(40), s.[ShipDate], 121), CONVERT(NVARCHAR(40), t.[ShipDate], 121))
) AS v(column_name, src_value, tgt_value)
WHERE EXISTS (SELECT v.src_value EXCEPT SELECT v.tgt_value)   -- NULL-safe "is different"
ORDER BY s.[OrderID], s.[LineNo], v.column_name;
