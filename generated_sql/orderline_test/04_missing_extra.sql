/* 04_missing_extra.sql
   Mapping : mappings/orderline_test.yaml  (dialect: sqlserver)
   Source  : stg.OrderLine
   Target  : dw.OrderLine
   Check   : Keys (OrderID, LineNo) that exist on only one side. MISSING_IN_TARGET = source only; EXTRA_IN_TARGET = target only.
   PASS    : No rows returned.
   NOTE    : Generated by generator/generate_sql.py. Not executed. Do not edit by hand;
             change the mapping and regenerate.
             DISTINCT keys are used so duplicates (see 03) do not repeat rows here.
             Rows with a NULL key never match; they are reported by 02_null_checks.sql. */

WITH s AS (SELECT DISTINCT [OrderID], [LineNo] FROM [stg].[OrderLine] WHERE [OrderID] IS NOT NULL AND [LineNo] IS NOT NULL),
     t AS (SELECT DISTINCT [OrderID], [LineNumber] AS [LineNo] FROM [dw].[OrderLine] WHERE [OrderID] IS NOT NULL AND [LineNumber] IS NOT NULL)
SELECT
    COALESCE(s.[OrderID], t.[OrderID]) AS [OrderID],
    COALESCE(s.[LineNo], t.[LineNo]) AS [LineNo],
    CASE WHEN t.[OrderID] IS NULL THEN 'MISSING_IN_TARGET'
         ELSE 'EXTRA_IN_TARGET' END AS issue
FROM s
FULL OUTER JOIN t
    ON s.[OrderID] = t.[OrderID]
   AND s.[LineNo] = t.[LineNo]
WHERE s.[OrderID] IS NULL
   OR t.[OrderID] IS NULL
ORDER BY issue, [OrderID], [LineNo];
